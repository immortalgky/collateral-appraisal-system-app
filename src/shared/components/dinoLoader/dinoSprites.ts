/**
 * Pixel art for the dino loader, stored as string rows: '#' is ink, '.' is transparent.
 *
 * All of it is original work. No part of Chrome's offline.png / 100-offline-sprite.png is
 * used or derived from. The grids were authored in docs/poc/dino-loader-mock.html, which
 * still carries the live editor if any of them needs nudging.
 *
 * This module is pure data — it must not touch the DOM. Rows are compiled into canvases by
 * buildSpriteSet in ./dinoRenderer.
 */

export type PixelRows = readonly string[];

/** Width/height of a sprite in *sprite pixels* (multiply by the pixel scale for CSS px). */
export function spriteSize(rows: PixelRows): { w: number; h: number } {
  return { w: rows[0].length, h: rows.length };
}

